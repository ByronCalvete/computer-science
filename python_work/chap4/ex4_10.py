sports = ['futbol', 'baseball', 'basketball', 'hockey', 'ping pong']

print('These are the first three elements of the list:')
print(sports[:3]) # ['futbol', 'baseball', 'basketball']

print('\nThese are the three middle elements of the list:')
print(sports[1:4]) # ['baseball', 'basketball', 'hockey']

print('\nThese are the last three elements of the list:')
print(sports[-3:]) # ['basketball', 'hockey', 'ping pong']
